/*
 * Regenerate `src/icons.js` from the Phosphor SVGs that ship with the editor.
 *
 *     node build-icons.mjs
 *
 * The websites draw the same glyphs the tool shelf draws, from the same files,
 * so a docs page that labels the Lasso cannot drift from the icon beside it in
 * the app. Icons are inlined as path data rather than fetched as files: they
 * are a few hundred bytes each, they must inherit `currentcolor`, and a
 * sprite sheet would be one more request for no benefit at this size.
 */

