/** Pull the geometry out of a Phosphor file, dropping its `<svg>` wrapper. */
function extractBody(svg) {
  const open = svg.indexOf(">", svg.indexOf("<svg"));
  const close = svg.lastIndexOf("</svg>");
  if (open === -1 || close === -1) {
    throw new Error("not an svg");
  }
  return svg
    .slice(open + 1, close)
    .replace(/\s+fill="currentColor"/g, "")
    .trim();
}

const entries = WANTED.map((name) => {
  const svg = readFileSync(join(source, `${name}.svg`), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(extractBody(svg))},`;
}).join("\n");

const out = `/*
 * Phosphor Icons 2.1.1 (MIT) — https://phosphoricons.com
 *
 * GENERATED by build-icons.mjs from assets/icons/phosphor/regular. Do not edit
 * by hand: add the stem to WANTED in that script and run it again.
 *
 * Each value is the inside of a 0 0 256 256 <svg>, with the upstream
 * fill="currentColor" stripped so the CSS decides the colour.
 */

/** @type {Record<string, string>} */
export const ICONS = {
${entries}
};

/** Every stem this bundle carries, for the guard test in the sites. */
export const ICON_NAMES = Object.keys(ICONS);
`;

writeFileSync(join(here, "src/icons.js"), out);
